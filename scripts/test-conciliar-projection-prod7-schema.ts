/* Prueba estática pura: no importa Prisma, handlers, red ni base de datos. */
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
const root = resolve(__dirname, '..')
const read = (path: string) => readFileSync(resolve(root, path), 'utf8')
const db = read('lib/finanzas/conciliar-db.ts')
const reader = read('lib/finanzas/conciliar-projection-read.ts')
const refresh = read('lib/finanzas/conciliar-affected-refresh.ts')
const actions = read('lib/finanzas/conciliar-actions.ts')
const route = read('app/api/admin/finanzas/conciliar/route.ts')
const workMigration = read('prisma/migrations/20261030_area3_conciliar_work_projection/migration.sql')
const recoveryMigration = read('prisma/migrations/20261031_area3_conciliar_receipt_recovery/migration.sql')
for (const source of [db, reader, refresh, actions, route]) {
  assert.doesNotMatch(source, /conciliar-document-lifecycle-guard|document_version_|area3_received_document_hashes/, 'runtime no vuelve a la superficie congelada')
}
assert.match(workMigration, /ADD COLUMN read_metadata jsonb/)
assert.match(workMigration, /ADD COLUMN read_accounts jsonb/)
assert.match(workMigration, /CREATE TABLE area3_conciliar_projection_changes/)
assert.match(workMigration, /PRIMARY KEY\(kind,source_id\)/)
assert.match(recoveryMigration, /resolution" IN \('PENDING','COMMITTED'\)/)
const recoveryDdl = recoveryMigration.replace(/--[^\n]*/g, '')
assert.doesNotMatch(recoveryDdl, /NOT_COMMITTED/)
const readBundle = reader.slice(reader.indexOf('async function readProjectionBundle'), reader.indexOf('async function projectionResponse'))
assert.equal((readBundle.match(/\bclient\.\$queryRaw/g) ?? []).length, 1, 'la portada conserva un único viaje SQL')
assert.match(readBundle, /p\.read_metadata/)
assert.match(readBundle, /read_accounts/)
assert.match(readBundle, /document_requests AS \(/)
assert.doesNotMatch(readBundle, /\b(?:INSERT|UPDATE|DELETE|rebuildConciliarProjection|fetch)\b/i, 'GET no escribe ni reconstruye')
const rebuild = db.slice(db.indexOf('export async function rebuildConciliarProjectionTx'), db.indexOf('export async function rebuildConciliarProjection('))
assert.match(rebuild, /applyConciliarDocumentSourceGuardToRebuildRowsTx/)
assert.match(rebuild, /const sealedRows = await sealConciliarProjectionRowsTx\(tx, guardedRows\)/)
assert.ok(rebuild.indexOf('const sealedRows = await sealConciliarProjectionRowsTx') < rebuild.indexOf('DELETE FROM conciliar_proyecciones'), 'G7 se sella antes de DML')
assert.match(rebuild, /materializeConciliarReadMetadataTx/)
assert.match(rebuild, /SET read_accounts=/)
assert.match(rebuild, /DELETE FROM area3_conciliar_projection_changes q/)
assert.match(rebuild, /dirty_at=CASE WHEN NOT EXISTS \(SELECT 1 FROM area3_conciliar_projection_changes\) THEN NULL/)
assert.match(refresh, /SELECT kind,source_id AS "sourceId" FROM area3_conciliar_projection_changes[\s\S]*FOR UPDATE/)
assert.match(refresh, /const consumedChanges: readonly ConciliarProjectionChange\[\]/)
assert.match(refresh, /rebuildConciliarProjectionTx\(tx, actorId, scope\)/)
assert.doesNotMatch(refresh, /\b(fetch|https?:|azure|graph|mail|correo|webhook|sync|importar)\b/i)
assert.match(actions, /conciliarDocumentSourceGuardMessage/)
assert.doesNotMatch(actions, /conciliarDocumentLifecycleGuardMessage|lockConciliarDocumentLifecycle/)
assert.match(route, /scheduleConciliarActionProjectionRefresh/)
console.log(JSON.stringify({ test: 'conciliar-projection-v2-readside', databaseQueries: 0, networkCalls: 0, verified: ['additive-work-queue', 'precomputed-read-metadata-and-accounts', 'g7-before-dml', 'affected-refresh', 'frozen-version-negative'] }))
